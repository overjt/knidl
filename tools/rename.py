#!/usr/bin/env python3
"""rename.py - give a function or a data symbol a real name everywhere it lives.

Usage:
    tools/rename.py OLD NEW --evidence TEXT [--kind KIND] [--write]
    tools/rename.py --csv FILE [--write]

Dry run by default: it validates every rename and prints what it would touch.
With --write it applies them.  A CSV has the header `old,new,kind,evidence`
and an optional `issue` column (default --issue, 155).  Naming rules:
docs/naming.md.

A name lives in these places, and the tool updates all of them:
  * tools/symdb.py: a function's name is its KNOWN_SYMBOLS entry (or its
    ARM_ENTRIES tuple), so docs/analysis/symbols.csv regenerates with it;
  * tools/split_config.json: data_symbols values, extra_labels values,
    abs_symbols keys, external_defined (kept sorted), and every mention in
    the pointer_tables / not_pointers reasons and the comment;
  * every word-boundary use in src/ and include/, tools/header_smoke.c,
    linker.ld (the MATCHING asserts name the first symbol of each grouped
    run since #36 phase 2 run 3; section names and object paths are not
    symbols) and the hand-written asm (asm/*.s without split.py's
    "Auto-generated" header).  sub_/gUnk_ names match with either hex case.  A name used as
    a file name (`src/sub_0804e3a0.c`, `.sub_0804e3a0` sections) is not a
    symbol and is left alone.
  * docs/analysis/renames.csv gets one `old,new,kind,evidence,issue` row
    per rename.  It is the alias table: the lessons, rom-map and
    module-map keep the names of their time.

It never edits generated files.  After --write, regenerate and prove the ROM:
    make symbols && make split && make modmap
    make clean && make compare
(--regen runs exactly that and stops at the first failure.)  Then
    tools/rename.py --verify-diff master
proves the branch is a pure rename: every name renames.csv gained since the
ref is mapped back, and the code (outside comments), the generated files
and the config must come out identical to the ref's.

Validation, per rename: OLD resolves (a symbols.csv function, a
data_symbols / extra_labels name or an abs_symbols constant); the kind
matches the address; NEW is a C identifier, not a keyword, not a
placeholder prefix (sub_, gUnk_, unk_, loc_, _), follows docs/naming.md's
style for its kind (--allow-style for a public reference such as an SDK
name), and is not already an identifier anywhere in the tree (any case).
Evidence is required.
"""

import argparse
import csv
import importlib.util
import io
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SYMDB = os.path.join(ROOT, "tools", "symdb.py")
CONFIG = os.path.join(ROOT, "tools", "split_config.json")
SYMBOLS = os.path.join(ROOT, "docs", "analysis", "symbols.csv")
RENAMES = os.path.join(ROOT, "docs", "analysis", "renames.csv")
TEXT_DIRS = ("src", "include")
TEXT_FILES = ("tools/header_smoke.c", "linker.ld")
GENERATED_MARK = "Auto-generated by tools/split.py"

KINDS = ("function", "ram", "io", "rom", "const")

C_KEYWORDS = set("""
auto break case char const continue default do double else enum extern float
for goto if inline int long register restrict return short signed sizeof
static struct switch typedef union unsigned void volatile while asm typeof
_Bool _Complex _Imaginary __asm__ __attribute__ __inline__ __volatile__
u8 u16 u32 u64 s8 s16 s32 s64 vu8 vu16 vu32 vs8 vs16 vs32 bool8 bool16
bool32 TRUE FALSE NULL main
""".split())

PLACEHOLDER_RE = re.compile(r"^(?:sub_|gUnk_|unk_|loc_|_|nullsub)", re.I)
IDENT_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
# docs/naming.md section 2.  Underscores separate PascalCase words of one
# family (Task_Foo, gMPlayInfo_BGM); every segment starts with a capital or a
# digit.
STYLE = {
    "function": re.compile(r"^[A-Z][A-Za-z0-9]*(?:_[A-Z0-9][A-Za-z0-9]*)*$"),
    "ram": re.compile(r"^[gs][A-Z][A-Za-z0-9]*(?:_[A-Z0-9][A-Za-z0-9]*)*$"),
    "io": re.compile(r"^(?:[gs][A-Z][A-Za-z0-9]*|REG_[A-Z0-9_]+)$"),
    "rom": re.compile(r"^[gs][A-Z][A-Za-z0-9]*(?:_[A-Z0-9][A-Za-z0-9]*)*$"),
    "const": re.compile(r"^(?:[A-Z][A-Z0-9_]*|g[A-Z][A-Za-z0-9]*)$"),
}
ADDR_NAME_RE = re.compile(r"^(sub|gUnk)_([0-9A-Fa-f]{8})$")
TOKEN_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")


class RenameError(Exception):
    pass


def rel(path):
    return os.path.relpath(path, ROOT)


def load_symdb_module():
    spec = importlib.util.spec_from_file_location("symdb", SYMDB)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def text_files():
    """Hand-maintained files whose identifiers the tool rewrites."""
    out = []
    for d in TEXT_DIRS:
        for base, dirs, files in os.walk(os.path.join(ROOT, d)):
            dirs.sort()
            for f in sorted(files):
                if f.endswith((".c", ".h", ".inc", ".s")):
                    out.append(os.path.join(base, f))
    for f in TEXT_FILES:
        out.append(os.path.join(ROOT, f))
    asm_dir = os.path.join(ROOT, "asm")
    for f in sorted(os.listdir(asm_dir)):
        p = os.path.join(asm_dir, f)
        if f.endswith(".s") and os.path.isfile(p):
            with open(p, encoding="utf-8") as fh:
                head = fh.read(512)
            if GENERATED_MARK not in head:
                out.append(p)
    return out


C_COMMENT_RE = re.compile(r"/\*.*?\*/|//[^\n]*", re.S)
ASM_COMMENT_RE = re.compile(r"/\*.*?\*/|@[^\n]*", re.S)


def collapse_ws(text):
    return re.sub(r"\s+", " ", text).strip()


def comments_of(text, is_asm):
    return (ASM_COMMENT_RE if is_asm else C_COMMENT_RE).findall(text)


def strip_comments(text, is_asm):
    return (ASM_COMMENT_RE if is_asm else C_COMMENT_RE).sub(" ", text)


def file_stems():
    """Names that are also file names (src/sub_0804e3a0.c): not symbols there."""
    stems = set()
    for d in TEXT_DIRS + ("asm", "data"):
        for base, _, files in os.walk(os.path.join(ROOT, d)):
            stems.update(os.path.splitext(f)[0] for f in files)
    return stems


def key_of(name):
    """Normalised lookup key: sub_/gUnk_ hex compares case-insensitively."""
    m = ADDR_NAME_RE.match(name)
    if m:
        return "%s_%s" % (m.group(1), m.group(2).lower())
    return name


def name_pattern(names, stems=()):
    """One regex for every old name, word-bounded.  A name that is also a
    file stem does not match as a path (`src/<name>.c`, `.<name>`)."""
    lower_stems = set(s.lower() for s in stems)
    alts = []
    for n in sorted(names, key=len, reverse=True):
        m = ADDR_NAME_RE.match(n)
        if m:
            alt = "%s_(?i:%s)" % (m.group(1), m.group(2))
        else:
            alt = re.escape(n)
        if n.lower() in lower_stems:
            alt = r"(?<![/.])%s(?!\.(?:c|h|o|s)\b)" % alt
        alts.append(alt)
    return re.compile(r"(?<![A-Za-z0-9_])(?:%s)(?![A-Za-z0-9_])" % "|".join(alts))


class State:
    def __init__(self):
        self.symdb = load_symdb_module()
        with open(SYMDB, encoding="utf-8") as f:
            self.symdb_text = f.read()
        with open(CONFIG, encoding="utf-8") as f:
            self.config_text = f.read()
        self.config = json.loads(self.config_text)
        if json.dumps(self.config, indent=2) + "\n" != self.config_text:
            raise RenameError(
                "tools/split_config.json does not round-trip through "
                "json.dumps(indent=2); refusing to rewrite it")
        self.functions = {}  # name -> (vma, isa)
        with open(SYMBOLS, encoding="utf-8") as f:
            for row in csv.DictReader(f):
                self.functions[row["name"]] = (int(row["vma"], 16), row["isa"])
        self.data = {}  # name -> addr   (data_symbols and extra_labels)
        for k, v in self.config.get("data_symbols", {}).items():
            self.data[v] = int(k, 16)
        self.labels = {}
        for k, v in self.config.get("extra_labels", {}).items():
            self.labels[v] = int(k, 16)
        self.consts = dict(self.config.get("abs_symbols", {}))
        self.files = text_files()
        self.contents = {}
        for p in self.files:
            with open(p, encoding="utf-8") as f:
                self.contents[p] = f.read()
        # Every identifier already in use (outside comments), compared
        # case-insensitively; words that only occur in comments are noted.
        used = set()
        self.comment_words = set()
        for p, text in self.contents.items():
            code = strip_comments(text, p.endswith(".s"))
            used.update(TOKEN_RE.findall(code))
            self.comment_words.update(TOKEN_RE.findall(text))
        used.update(self.functions)
        used.update(self.data)
        used.update(self.labels)
        used.update(self.consts)
        used.update(self.config.get("external_defined", []))
        used.update(self.symdb.KNOWN_SYMBOLS.values())
        used.update(n for _, _, n in self.symdb.ARM_ENTRIES if n)
        self.used_lower = {}
        for n in used:
            self.used_lower.setdefault(n.lower(), set()).add(n)

    def resolve(self, old):
        """(kind, address) of a name, or raise."""
        if old in self.functions:
            return "function", self.functions[old][0]
        for table in (self.data, self.labels):
            if old in table:
                addr = table[old]
                if addr >= 0x08000000:
                    kind = "rom"
                elif 0x04000000 <= addr < 0x05000000:
                    kind = "io"
                else:
                    kind = "ram"
                return kind, addr
        if old in self.consts:
            return "const", int(self.consts[old], 16)
        raise RenameError(
            "%s: not a symbols.csv function, a data_symbols/extra_labels "
            "name or an abs_symbols constant" % old)


def validate(state, rows, allow_style):
    """Check every row; returns the list of resolved renames."""
    seen_old, seen_new = {}, {}
    out = []
    for i, r in enumerate(rows, 1):
        old, new = r["old"].strip(), r["new"].strip()
        where = "row %d (%s -> %s)" % (i, old, new)
        ev = (r.get("evidence") or "").strip()
        if not ev:
            raise RenameError("%s: evidence is required" % where)
        kind, addr = state.resolve(old)
        want = (r.get("kind") or "").strip()
        if want and want != kind:
            raise RenameError("%s: kind %r, but %s is a %s at 0x%08X"
                              % (where, want, old, kind, addr))
        if not IDENT_RE.match(new):
            raise RenameError("%s: %r is not a C identifier" % (where, new))
        if new in C_KEYWORDS:
            raise RenameError("%s: %r is a keyword or a repo type" % (where, new))
        if PLACEHOLDER_RE.match(new):
            raise RenameError("%s: %r uses a placeholder prefix" % (where, new))
        if not STYLE[kind].match(new):
            msg = ("%s: %r does not follow docs/naming.md's %s style"
                   % (where, new, kind))
            if not allow_style:
                raise RenameError(msg + " (--allow-style for a public name)")
            print("warning: " + msg, file=sys.stderr)
        clash = state.used_lower.get(new.lower(), set()) - {old}
        if clash:
            raise RenameError("%s: %r is already used in the tree (%s)"
                              % (where, new, ", ".join(sorted(clash))))
        if new in state.comment_words:
            print("note: %s already appears in a comment (check it names "
                  "the same thing)" % new, file=sys.stderr)
        if key_of(old) in seen_old:
            raise RenameError("%s: %s is renamed twice" % (where, old))
        if new.lower() in seen_new:
            raise RenameError("%s: %s is given twice (row %d)"
                              % (where, new, seen_new[new.lower()]))
        if new in state.functions or new in state.data or new in state.labels:
            raise RenameError("%s: %s is already a symbol" % (where, new))
        seen_old[key_of(old)] = i
        seen_new[new.lower()] = i
        issue = (r.get("issue") or "").strip() or r["_issue"]
        out.append({"old": old, "new": new, "kind": kind, "addr": addr,
                    "evidence": ev, "issue": issue})
    olds = {key_of(x["old"]) for x in out}
    for x in out:
        if key_of(x["new"]) in olds:
            raise RenameError("%s -> %s: a rename chain inside one batch; "
                              "apply it in two batches" % (x["old"], x["new"]))
    return out


# ---- tools/symdb.py ----------------------------------------------------------

BLOCK_BEGIN = "    # ---- names given with tools/rename.py (issue #155 onwards) ----"
BLOCK_NOTE = ("    # Each name's evidence is its row in docs/analysis/renames.csv;\n"
              "    # kept sorted by address, tools/rename.py inserts here.\n")
BLOCK_END = "    # ---- end of tools/rename.py names ----"


def edit_symdb(text, known, arm_names, renames):
    lines = text.split("\n")
    try:
        start = lines.index("KNOWN_SYMBOLS = {")
    except ValueError:
        raise RenameError("tools/symdb.py: no `KNOWN_SYMBOLS = {` line")
    end = start + lines[start:].index("}")
    if BLOCK_BEGIN not in lines[start:end]:
        lines[end:end] = [BLOCK_BEGIN] + BLOCK_NOTE.rstrip("\n").split("\n") + [BLOCK_END]
        end += 2 + BLOCK_NOTE.count("\n")
    b0 = lines.index(BLOCK_BEGIN, start)
    b1 = lines.index(BLOCK_END, b0)
    entry_re = re.compile(r'^    (0x[0-9A-F]{8}): "([^"]+)",$')
    block = {}
    for ln in lines[b0 + 1:b1]:
        m = entry_re.match(ln)
        if m:
            block[int(m.group(1), 16)] = m.group(2)
    note = lines[b0 + 1:b0 + 1 + BLOCK_NOTE.count("\n")]
    for r in renames:
        if r["kind"] != "function":
            continue
        vma, old, new = r["addr"], r["old"], r["new"]
        if vma in block:
            block[vma] = new
        elif vma in known:
            pat = re.compile(r'(0x%08X:\s*)"%s"' % (vma, re.escape(known[vma])))
            body = "\n".join(lines)
            body, n = pat.subn(lambda m: m.group(1) + '"%s"' % new, body)
            if n != 1:
                raise RenameError("tools/symdb.py: KNOWN_SYMBOLS entry for "
                                  "0x%08X not found once (%d)" % (vma, n))
            lines = body.split("\n")
        elif vma in arm_names:
            pat = re.compile(r'(\(0x%08X, 0x[0-9A-Fa-f]+, )(None|"%s")(\))'
                             % (vma, re.escape(arm_names[vma] or "")))
            body = "\n".join(lines)
            body, n = pat.subn(lambda m: m.group(1) + '"%s"' % new + m.group(3), body)
            if n != 1:
                raise RenameError("tools/symdb.py: ARM_ENTRIES tuple for "
                                  "0x%08X not found once (%d)" % (vma, n))
            lines = body.split("\n")
        else:
            block[vma] = new
        b0 = lines.index(BLOCK_BEGIN)
        b1 = lines.index(BLOCK_END, b0)
    b0 = lines.index(BLOCK_BEGIN)
    b1 = lines.index(BLOCK_END, b0)
    body = ['    0x%08X: "%s",' % (v, n) for v, n in sorted(block.items())]
    lines[b0 + 1:b1] = note + body
    return "\n".join(lines)


# ---- tools/split_config.json -------------------------------------------------

def edit_config(config, pattern, mapping):
    def sub(s):
        return pattern.sub(lambda m: mapping[key_of(m.group(0))], s)

    def walk(x):
        if isinstance(x, str):
            return sub(x)
        if isinstance(x, list):
            return [walk(v) for v in x]
        if isinstance(x, dict):
            return dict((sub(k), walk(v)) for k, v in x.items())
        return x

    out = walk(config)
    out["external_defined"] = sorted(out.get("external_defined", []))
    return out


# ---- driver ------------------------------------------------------------------

def run(state, renames, write):
    mapping = dict((key_of(r["old"]), r["new"]) for r in renames)
    pattern = name_pattern([r["old"] for r in renames], file_stems())
    counts = dict((key_of(r["old"]), 0) for r in renames)
    changed = {}
    for p, text in state.contents.items():
        def repl(m):
            counts[key_of(m.group(0))] += 1
            return mapping[key_of(m.group(0))]
        new_text = pattern.sub(repl, text)
        if new_text != text:
            changed[p] = new_text
    known = dict(state.symdb.KNOWN_SYMBOLS)
    arm_names = dict((v, n) for v, _, n in state.symdb.ARM_ENTRIES)
    symdb_text = edit_symdb(state.symdb_text, known, arm_names, renames)
    config = edit_config(state.config, pattern, mapping)
    config_text = json.dumps(config, indent=2) + "\n"
    # Left-over check: the old names must be gone from every edited place
    # except file names.
    for p, text in list(changed.items()) + [(CONFIG, config_text)]:
        left = pattern.findall(text)
        if left:
            raise RenameError("%s: %s still present after the rename"
                              % (rel(p), ", ".join(sorted(set(left)))))
    for r in renames:
        n = counts[key_of(r["old"])]
        print("%-8s 0x%08X  %-14s -> %-32s %4d uses" % (
            r["kind"], r["addr"], r["old"], r["new"], n))
    print("files: %d source/header/asm, %s, %s, %s" % (
        len(changed), rel(SYMDB), rel(CONFIG), rel(RENAMES)))
    if not write:
        print("dry run: nothing written (use --write)")
        return
    for p, text in changed.items():
        with open(p, "w", encoding="utf-8") as f:
            f.write(text)
    with open(SYMDB, "w", encoding="utf-8") as f:
        f.write(symdb_text)
    with open(CONFIG, "w", encoding="utf-8") as f:
        f.write(config_text)
    new_file = not os.path.exists(RENAMES)
    with open(RENAMES, "a", encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        if new_file:
            w.writerow(["old", "new", "kind", "evidence", "issue"])
        for r in renames:
            w.writerow([r["old"], r["new"], r["kind"], r["evidence"], r["issue"]])
    print("wrote %d renames; now run: make symbols && make split && make "
          "modmap && make clean && make compare" % len(renames))


def verify_diff(ref):
    """Prove that every change since the git ref REF is a logged rename.

    Applies every rename renames.csv gained since REF to REF's copy of each
    file and compares it with the tree: C/asm code outside comments must be identical
    (comment edits are listed for review), generated files identical,
    split_config.json and tools/symdb.py identical as line multisets except
    for the KNOWN_SYMBOLS entries of the renamed functions."""
    def git(*args):
        res = subprocess.run(["git"] + list(args), cwd=ROOT,
                             stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                             universal_newlines=True)
        if res.returncode != 0:
            raise RenameError("git %s: %s" % (" ".join(args), res.stderr.strip()))
        return res.stdout

    renames_rel = rel(RENAMES)
    try:
        before = list(csv.DictReader(io.StringIO(git("show", "%s:%s" % (ref, renames_rel)))))
    except RenameError:
        before = []
    with open(RENAMES, encoding="utf-8") as f:
        now = list(csv.DictReader(f))
    if now[:len(before)] != before:
        raise RenameError("%s: rows before %s were edited, not appended" % (renames_rel, ref))
    added = now[len(before):]
    fields = [r for r in added if r["kind"] == "field"]
    added = [r for r in added if r["kind"] != "field"]
    field_pairs = compose_field_renames(fields)
    field_uses = {}
    # Compose the renames since REF into one forward map (old -> final name),
    # following chains (A -> B, then B -> C), and apply it to REF's text the
    # way the tool does.  Mapping back instead would be lossy wherever a new
    # name already appeared in prose before the rename.
    fwd = {}
    for r in added:
        for k, v in list(fwd.items()):
            if v == r["old"]:
                fwd[k] = r["new"]
        fwd.setdefault(key_of(r["old"]), r["new"])
    if fwd:
        pattern = name_pattern([r["old"] for r in added], file_stems())
        remap = lambda s: pattern.sub(lambda m: fwd[key_of(m.group(0))], s)
    else:
        remap = lambda s: s
    fwd_names = set(fwd.values())
    arm_re = re.compile(r'^    \(0x([0-9A-F]{8}), 0x[0-9A-Fa-f]+, (None|"\w+")\),')
    block_re = re.compile(r'^    0x([0-9A-F]{8}): "(\w+)",$')
    status = git("diff", "--name-status", ref, "--").split("\n")
    status += ["A\t" + p for p in git("ls-files", "--others", "--exclude-standard").split("\n") if p]
    surface = ("src/", "include/", "asm/", "data/", "docs/analysis/symbols.csv",
               "docs/analysis/callgraph.csv", "docs/analysis/module-map.csv",
               rel(CONFIG), rel(SYMDB)) + TEXT_FILES
    comment_only, checked, problems, outside = [], 0, [], []
    for line in status:
        if not line.strip():
            continue
        code, path = line.split("\t", 1)
        if path == renames_rel:
            continue
        if not path.startswith(surface):
            outside.append(path)
            continue
        if code != "M":
            problems.append("%s: %s (only modified files are expected)" % (path, code))
            continue
        checked += 1
        old = git("show", "%s:%s" % (ref, path))
        if path != rel(SYMDB):
            # tools/symdb.py: the tool edits only KNOWN_SYMBOLS/ARM_ENTRIES
            # entries, never its comments, so compare it unmapped.
            old = remap(old)
        with open(os.path.join(ROOT, path), encoding="utf-8") as f:
            new = f.read()
        if path == rel(CONFIG):
            # Compare the config structurally: the tool re-sorts
            # external_defined, which moves JSON's comma-less last line.
            want = json.loads(old)
            want["external_defined"] = sorted(want.get("external_defined", []))
            if want != json.loads(new):
                problems.append("%s: differs beyond the renames" % path)
            continue
        if path == rel(SYMDB):
            a = sorted(old.split("\n"))
            b = sorted(new.split("\n"))
            extra = []
            for ln in b:
                if ln in a:
                    a.remove(ln)
                else:
                    extra.append(ln)
            def named_here(ln):
                # A KNOWN_SYMBOLS entry or an ARM_ENTRIES tuple that gives a
                # renamed address its new name.
                m = block_re.match(ln) or arm_re.match(ln)
                return bool(m) and m.group(2).strip('"') in fwd_names
            bad = [ln for ln in extra if not (named_here(ln)
                   or ln in (BLOCK_BEGIN, BLOCK_END) or ln in BLOCK_NOTE.split("\n"))]
            def renamed_away(ln):
                # The old form of a KNOWN_SYMBOLS entry or ARM_ENTRIES tuple
                # the tool gave a new name.
                m = block_re.match(ln) or arm_re.match(ln)
                if not m:
                    return False
                key = "sub_" + m.group(1).lower()
                return key in fwd or key_of(m.group(2).strip('"')) in fwd
            a = [ln for ln in a if not renamed_away(ln)]
            if a or bad:
                problems.append("%s: lines beyond the renames: -%d +%d (%s)" % (
                    path, len(a), len(bad), (a + bad)[:3]))
            continue
        if path.endswith((".c", ".h", ".s", ".inc")):
            is_asm = path.endswith(".s")
            a, b = strip_comments(old, is_asm), strip_comments(new, is_asm)
            if not is_asm:
                # C is free-form: an added or removed comment leaves a
                # different run of whitespace behind, which is not a code
                # change.  (make compare remains the byte-level proof.)
                a, b = collapse_ws(a), collapse_ws(b)
            if a != b and not (field_pairs and not is_asm
                               and fields_only_differ(a, b, field_pairs, field_uses)):
                problems.append("%s: code differs beyond the renames" % path)
            elif ([qualify_fields(c, field_pairs) for c in comments_of(old, is_asm)]
                  != comments_of(new, is_asm)):
                comment_only.append(path)
            continue
        if old != new:
            problems.append("%s: differs beyond the renames" % path)
    print("verify-diff %s: %d renames, %d field renames, %d files checked"
          % (ref, len(added), len(fields), checked))
    for (tag, o), n in sorted(field_pairs.items()):
        if not field_uses.get((o, n)):
            problems.append("field %s.%s -> %s: no use renamed" % (tag, o, n))
    for p in comment_only:
        print("  comment edits (review them): %s" % p)
    for p in outside:
        print("  outside the rename surface (docs/tooling, not checked): %s" % p)
    for p in problems:
        print("  PROBLEM: %s" % p)
    if problems:
        raise RenameError("the diff since %s is not a pure rename" % ref)
    print("verify-diff: OK - code and generated files differ only by the renames")


# ---- field renames (tools/rename_field.py) -------------------------------------

def compose_field_renames(rows):
    """{(struct tag, original member): final member} from renames.csv rows of
    kind `field` (`Struct.old` -> `Struct.new`), following chains."""
    fwd = {}
    for r in rows:
        tag, old = r["old"].split(".", 1)
        tag2, new = r["new"].split(".", 1)
        if tag != tag2:
            raise RenameError("field rename %s -> %s changes the struct" % (r["old"], r["new"]))
        hit = False
        for k, v in list(fwd.items()):
            if k[0] == tag and v == old:
                fwd[k] = new
                hit = True
        if not hit:
            fwd.setdefault((tag, old), new)
    return fwd


def qualify_fields(comment, pairs):
    """rename_field.py's comment rule: `Struct.old` -> `Struct.new`."""
    for (tag, o), n in pairs.items():
        comment = re.sub(r"(?<![A-Za-z0-9_])%s\.%s(?![A-Za-z0-9_])" % (
            re.escape(tag), re.escape(o)), tag + "." + n, comment)
    return comment


FIELD_SPLIT_RE = re.compile(r"([A-Za-z_][A-Za-z0-9_]*)")


def fields_only_differ(a, b, pairs, uses):
    """True if the comment-stripped texts a (the ref, symbols remapped) and b
    (the tree) differ only by logged field renames: every differing
    identifier is a (member, new member) pair of `pairs`, and sits after `.`
    or `->` (an access or a designated initializer) or is a member
    declarator inside `struct <tag> { ... }` of that pair's struct."""
    pa, pb = FIELD_SPLIT_RE.split(a), FIELD_SPLIT_RE.split(b)
    if len(pa) != len(pb):
        return False
    by_pair = {}
    for (tag, o), n in pairs.items():
        by_pair.setdefault((o, n), set()).add(tag)
    depth = 0
    stack = []      # (tag, depth of its body)
    pending = None  # tag of a `struct TAG` whose `{` may follow
    found = {}
    for i, (x, y) in enumerate(zip(pa, pb)):
        if i % 2 == 0:
            if x != y:
                return False
            for ch in x:
                if ch == "{":
                    depth += 1
                    if pending is not None:
                        stack.append((pending, depth))
                        pending = None
                elif ch == "}":
                    while stack and stack[-1][1] >= depth:
                        stack.pop()
                    depth -= 1
                elif not ch.isspace():
                    pending = None
            continue
        if pending == "":
            pending = x          # the tag after `struct` / `union`
        elif x in ("struct", "union"):
            pending = ""
        else:
            pending = None
        if x == y:
            continue
        tags = by_pair.get((x, y))
        if not tags:
            return False
        prev = pa[i - 1].rstrip()
        if not (prev.endswith(".") or prev.endswith("->")
                or (stack and stack[-1][0] in tags)):
            return False
        found[(x, y)] = found.get((x, y), 0) + 1
    for k, v in found.items():
        uses[k] = uses.get(k, 0) + v
    return True


def regen():
    for cmd in (["make", "symbols"], ["make", "split"], ["make", "modmap"],
                ["make", "clean"], ["make", "compare"]):
        print("+ " + " ".join(cmd), flush=True)
        res = subprocess.run(cmd, cwd=ROOT, stdout=subprocess.PIPE,
                             stderr=subprocess.STDOUT, universal_newlines=True)
        tail = res.stdout.strip().split("\n")[-3:]
        print("\n".join("  " + t for t in tail))
        if res.returncode != 0:
            sys.exit("rename.py: `%s` failed" % " ".join(cmd))


def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("old", nargs="?")
    ap.add_argument("new", nargs="?")
    ap.add_argument("--csv", help="batch file: old,new,kind,evidence[,issue]")
    ap.add_argument("--kind", choices=KINDS, help="expected kind (checked)")
    ap.add_argument("--evidence", help="why the name is right (required)")
    ap.add_argument("--issue", default="155", help="issue number for renames.csv")
    ap.add_argument("--allow-style", action="store_true",
                    help="accept a public name outside docs/naming.md's style")
    ap.add_argument("--write", action="store_true", help="apply (default: dry run)")
    ap.add_argument("--regen", action="store_true",
                    help="after --write, run make symbols/split/modmap, "
                         "make clean and make compare")
    ap.add_argument("--verify-diff", metavar="REF",
                    help="check that every change since git REF is a rename "
                         "logged in renames.csv (nothing else)")
    args = ap.parse_args()
    if args.verify_diff:
        try:
            verify_diff(args.verify_diff)
        except RenameError as e:
            sys.exit("rename.py: error: %s" % e)
        return
    if args.csv:
        if args.old or args.new:
            ap.error("give either OLD NEW or --csv, not both")
        with open(args.csv, encoding="utf-8") as f:
            rows = [r for r in csv.DictReader(f) if (r.get("old") or "").strip()
                    and not r["old"].lstrip().startswith("#")]
    else:
        if not (args.old and args.new):
            ap.error("OLD and NEW are required without --csv")
        rows = [{"old": args.old, "new": args.new, "kind": args.kind or "",
                 "evidence": args.evidence or ""}]
    for r in rows:
        r["_issue"] = args.issue
    try:
        state = State()
        renames = validate(state, rows, args.allow_style)
        run(state, renames, args.write)
    except RenameError as e:
        sys.exit("rename.py: error: %s" % e)
    if args.write and args.regen:
        regen()


if __name__ == "__main__":
    main()
