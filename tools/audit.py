#!/usr/bin/env python3
"""The final audit (issue #37): what the matching source still holds that is
not plain, named C, each item listed with its reason.

`make audit` runs it; it needs no baserom and no build (it reads the
committed tree only), so CI runs it on every push.  The checks:

  1. `.incbin`: only `baserom.gba` slices in `data/*.s` (structure-only data,
     docs/data.md) and the Nintendo logo in `asm/rom_header.s`; none in the
     rest of `asm/`, in `src/` or in `include/`.
  2. Raw numeric directives in `asm/` (`.byte`, `.short`/`.hword`/`.2byte`,
     `.inst`, and `.word`/`.4byte`/`.long` with a number operand): each is
     an instruction or a symbol, or it carries a same-line `@ raw: <reason>`
     comment (for generated files, tools/split.py emits it).
  3. The sanctioned asm: every file in `asm/` carries a `@ Stays asm:`
     header comment in its first lines, and the enumerated list in
     docs/audit.md section 2 names exactly the files in `asm/`; its
     "excluded" rows equal `tools/calcrom.pl`'s `%decomp_excluded_asm`.
  4. Raw addresses in `src/` and the game headers `include/*.h`: no ROM
     (0x08-0x0D), SRAM (0x0E), EWRAM (0x02), IWRAM (0x03), I/O (0x04),
     palette (0x05), VRAM (0x06) or OAM (0x07) address as a bare number.
     Allowed: a comment containing `raw:` on the same line or the line
     above, and the last argument of CpuSet/CpuFastSet (a control word,
     not an address).  `include/gba/` defines the region macros and is
     exempt.
  5. Code exceptions: every `register ... asm("rN")` pin, `asm(...)`
     statement, `BLOCK_CROSS_JUMP` and zero-code `while (0)` in `src/` is a
     row of docs/audit.md section 3 (file:line or file:first-last, the
     enclosing function, a reason), and every row there still points at
     such a site (or, for kind `stand-in`, at a line of that function).
  6. The placeholder census: `sub_*` functions, `gUnk_*` RAM, I/O and ROM
     symbols, `unk*` struct fields and `loc_*` labels, by kind, category and
     zone, each category with its reason.  The generated summary lives in
     docs/naming.md between the `audit:placeholders` markers; the audit
     fails when the committed summary is stale (regenerate with `--write`).

Usage:
  python3 tools/audit.py            # check; exit 1 on any failure
  python3 tools/audit.py --write    # regenerate docs/naming.md's summary
  python3 tools/audit.py --list     # also print every listed item
"""

