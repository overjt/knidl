# 3. the sanctioned asm


def calcrom_excluded():
    text = read("tools/calcrom.pl")
    m = re.search(r"%decomp_excluded_asm\s*=\s*map\s*\{[^}]*\}\s*qw\(([^)]*)\)", text)
    if not m:
        raise SystemExit("tools/calcrom.pl: %decomp_excluded_asm not found")
    return set(m.group(1).split())


SANCTIONED_ROW_RE = re.compile(r"^\|\s*`asm/([\w./-]+\.s)`\s*\|\s*(excluded|data|symbols)\s*\|\s*(.+?)\s*\|\s*$")


def doc_section(text, number):
    """The body of `## <number>. ...` up to the next `## ` heading."""
    m = re.search(r"^## %s\. .*$" % re.escape(str(number)), text, re.M)
    if not m:
        return None
    rest = text[m.end():]
    n = re.search(r"^## ", rest, re.M)
    return rest[:n.start()] if n else rest


def check_sanctioned_asm(rep):
    files = [p[len("asm/"):] for p in files_under("asm", (".s",))]
    excluded = calcrom_excluded()
    lines = []
    doc = read(AUDIT_DOC) if os.path.exists(os.path.join(ROOT, AUDIT_DOC)) else ""
    body = doc_section(doc, 2) or ""
    rows = {}
    for line in body.split("\n"):
        m = SANCTIONED_ROW_RE.match(line)
        if m:
            rows[m.group(1)] = (m.group(2), m.group(3))
    if not rows:
        rep.fail("%s section 2 has no sanctioned-asm rows" % AUDIT_DOC)
    for f in files:
        if f not in rows:
            rep.fail("asm/%s is not listed in %s section 2" % (f, AUDIT_DOC))
    for f in rows:
        if f not in files:
            rep.fail("%s section 2 lists asm/%s, which does not exist" % (AUDIT_DOC, f))
    doc_excluded = {os.path.splitext(os.path.basename(f))[0]
                    for f, (kind, _) in rows.items() if kind == "excluded"}
    if doc_excluded != excluded:
        rep.fail("sanctioned asm: docs 'excluded' rows %s != tools/calcrom.pl %s"
                 % (sorted(doc_excluded), sorted(excluded)))
    missing_header = []
    for f in files:
        head = read("asm/" + f).split("\n")[:HEADER_LINES]
        if not any(l.strip().startswith(HEADER_MARK) for l in head):
            missing_header.append(f)
    for f in missing_header:
        rep.fail("asm/%s has no `%s <reason>` header comment" % (f, HEADER_MARK))
    for f in sorted(files):
        kind, why = rows.get(f, ("?", "?"))
        lines.append("  asm/%s: %s" % (f, kind))
    lines.insert(0, "files in asm/: %d; calcrom.pl excluded: %s; header comments missing: %d"
                 % (len(files), " ".join(sorted(excluded)), len(missing_header)))
    rep.section("3. The sanctioned asm", lines)
    return {"files": len(files), "excluded": sorted(excluded), "missing_header": len(missing_header)}


