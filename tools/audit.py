# 1. .incbin

INCBIN_RE = re.compile(r'^\s*\.incbin\s+"([^"]+)"\s*(?:,\s*([^,@]+))?(?:,\s*([^,@]+))?')
LOGO_INCBIN = ("asm/rom_header.s", "0x04", "0x9C")


def check_incbin(rep):
    ok_data = 0
    bad = []
    logo = 0
    for top in ("asm", "data", "src", "include"):
        for path in files_under(top, (".s", ".inc", ".c", ".h")):
            for ln, line in enumerate(read(path).split("\n"), 1):
                if ".incbin" not in line and "INCBIN" not in line:
                    continue
                code = line.split("@", 1)[0]
                if top in ("src", "include"):
                    if re.search(r"\.incbin|INCBIN", strip_c(line)):
                        bad.append("%s:%d: %s" % (path, ln, line.strip()))
                    continue
                m = INCBIN_RE.match(code)
                if not m:
                    if ".incbin" in code:
                        bad.append("%s:%d: %s" % (path, ln, line.strip()))
                    continue
                name = m.group(1)
                if path.startswith("data/") and name == "baserom.gba":
                    ok_data += 1
                elif (path, (m.group(2) or "").strip(), (m.group(3) or "").strip()) == LOGO_INCBIN \
                        and name == "baserom.gba":
                    logo += 1
                else:
                    bad.append("%s:%d: %s" % (path, ln, line.strip()))
    for b in bad:
        rep.fail(".incbin outside data/*.s and the header logo: " + b)
    if logo != 1:
        rep.fail("expected exactly one header-logo .incbin in asm/rom_header.s, found %d" % logo)
    rep.section("1. .incbin", [
        "baserom.gba slices in data/*.s: %d" % ok_data,
        "header logo slice (asm/rom_header.s, 0x04+0x9C): %d" % logo,
        "anywhere else (asm/, src/, include/): %d" % len(bad),
    ])
    return {"data_slices": ok_data, "logo": logo, "other": len(bad)}


