LABEL_RE = re.compile(r"^([A-Za-z_][\w.$]*):")
STRUCT_HEAD_RE = re.compile(r"\b(struct|union)\s*(\w+)?\s*(?:__attribute__\s*\(\([^)]*\)\)\s*)?$")
TOKEN_RE = re.compile(r"[{};]")
FIELD_NAME_RE = re.compile(r"\b(unk[0-9A-Fa-f]+)\s*(?:\[[^\]]*\]\s*)*(?::\s*\d+\s*)?$")


def struct_fields(path):
    """Yield (struct name, field name) for the unk* members of every struct
    or union defined in a C file; a member of a nested anonymous struct or
    union counts for the enclosing named one."""
    text = strip_c(read(path))
    stack = []  # struct name, or None for any other brace (body, initializer)
    last = 0
    for m in TOKEN_RE.finditer(text):
        chunk = text[last:m.start()]
        last = m.end()
        tok = m.group(0)
        if tok == "{":
            head = STRUCT_HEAD_RE.search(chunk)
            if head and not re.search(r"=\s*$", chunk):
                name = head.group(2)
                if name is None and stack and stack[-1] is not None:
                    name = stack[-1]
                stack.append(name or "?")
            else:
                stack.append(None)
        elif tok == "}":
            if stack:
                stack.pop()
        elif tok == ";":
            if stack and stack[-1] is not None:
                fm = FIELD_NAME_RE.search(chunk.strip())
                if fm:
                    yield stack[-1], fm.group(1)


def placeholder_census():
    rows = {}  # (kind, category) -> count
    by_zone = {}  # zone -> [functions, sub_]
    extra = {}
    unnamed = load_unnamed()
    seen = set()  # (kind, symbol) of the placeholders the census found
    missing = []  # placeholders with no unnamed.csv row

    def add(kind, cat, n=1):
        rows[(kind, cat)] = rows.get((kind, cat), 0) + n

    def reason(kind, symbol, fallback):
        """The census category of a placeholder: its unnamed.csv row's code
        once the file exists, else the run-6 category `fallback`."""
        if unnamed is None:
            return fallback
        seen.add((kind, symbol))
        r = unnamed.get((kind, symbol))
        if r is None:
            missing.append("%s %s" % (kind, symbol))
            return "%s:unexamined" % UNNAMED_KINDS[kind]
        return "%s:%s" % (UNNAMED_KINDS[kind], r[0])

    add("I/O register", "io", 0)  # a row even at 0, like loc

    # functions
    with open(os.path.join(ROOT, "docs/analysis/symbols.csv"), encoding="utf-8") as f:
        for row in csv.DictReader(f):
            addr = int(row["vma"], 16)
            zone = zone_of(addr)
            z = by_zone.setdefault(zone, [0, 0])
            z[0] += 1
            if row["name"].startswith("sub_"):
                z[1] += 1
                if zone in ("m4a", "sdk", "crt0"):
                    add("function", reason("function", row["name"], "fn-lib"))
                elif zone == "engine":
                    add("function", reason("function", row["name"], "fn-engine"))
                else:
                    add("function", reason("function", row["name"], "fn-game"))
    # RAM and I/O cells
    cfg = json.loads(read("tools/split_config.json"))
    positions = position_names()
    formats = position_names(format_only=True)
    ram_named = ram_unk = ram_pos = 0
    for addr, name in cfg["data_symbols"].items():
        region = int(addr, 16) >> 24
        if region in (2, 3):
            if name.startswith("gUnk_"):
                add("RAM cell", reason("ram", name, "ram"))
                ram_unk += 1
            elif name in positions:
                ram_pos += 1
            else:
                ram_named += 1
        elif region == 4 and name.startswith("gUnk_"):
            add("I/O register", "io")
    extra["ram"] = (ram_named, ram_unk, ram_pos)
    # ROM labels: every label of data/*.s, by segment; an unnamed functional
    # label is classed by its referrers (#155 run 7)
    assets = asset_segments()
    segs = load_segments()
    rrefs, rcount = rom_referrers()

    def rom_cat(name):
        cat = rom_label_class(name, rrefs, rcount)
        if cat == "rom-several" and unnamed is not None:
            return reason("rom", name, cat)
        return cat
    rom_named = rom_unk_asset = rom_unk_data = rom_pos = 0
    for path in files_under("data", (".s",)):
        seg = os.path.splitext(os.path.basename(path))[0]
        for line in read(path).split("\n"):
            # a zone's file holds one section per piece (#167)
            m = re.match(r"\s*\.section\s+\.(\w+)", line)
            if m:
                seg = m.group(1)
                continue
            m = LABEL_RE.match(line)
            if not m:
                continue
            name = m.group(1)
            if name == seg or name.startswith(".L"):
                continue
            if name in formats:
                rom_pos += 1
                add("ROM label", "rom-position-format")
            elif name in positions:
                rom_pos += 1
                add("ROM label", "rom-position")
            elif name.startswith("gUnk_"):
                if seg in assets:
                    rom_unk_asset += 1
                    add("ROM label", "rom-asset")
                else:
                    rom_unk_data += 1
                    add("ROM label", rom_cat(name))
            else:
                rom_named += 1
    # ROM labels the C tables of src/data/ define (c_data rows): they left
    # data/*.s but are still labels, named or not
    c_rows = [(s, e) for s, e, k, _n in segs if k == "c_data"]
    for addr, name in cfg["data_symbols"].items():
        a = int(addr, 16)
        if not any(s <= a < e for s, e in c_rows):
            continue
        if name in positions:
            rom_pos += 1
            add("ROM label", "rom-position")
        elif name.startswith("gUnk_"):
            rom_unk_data += 1
            add("ROM label", rom_cat(name))
        else:
            rom_named += 1
    extra["rom"] = (rom_named, rom_unk_asset, rom_unk_data, rom_pos)
    # struct fields
    header_structs = {}
    for path in files_under("include", (".h",)):
        if path.startswith("include/gba/"):
            continue
        for s, fld in struct_fields(path):
            if not fld.startswith("unk"):
                continue
            if s == "Task" and fld in TASK_FAMILY_FIELDS:
                add("struct field", "field-task-family")
            elif s == "PlayerState" and fld in ("unk14", "unk16"):
                add("struct field", "field-player-scratch")
            else:
                add("struct field", reason("field", "%s.%s" % (s, fld), "field-header"))
            header_structs[s] = header_structs.get(s, 0) + 1
    local = 0
    for path in files_under("src", (".c",)):
        for s, fld in struct_fields(path):
            if fld.startswith("unk"):
                local += 1
                if unnamed is None:
                    continue
                if s == "Task" and fld in TASK_FAMILY_FIELDS:
                    add("struct field", "field-task-family-local")
                else:
                    add("struct field", reason("field", "%s.%s" % (s, fld), "field-local"))
    if local and unnamed is None:
        add("struct field", "field-local", local)
    extra["missing"] = missing
    extra["stale"] = sorted("%s %s" % k for k in (unnamed or {}) if k not in seen and k[0] != "rom") + \
        sorted("rom %s" % s for k, s in (unnamed or {}) if k == "rom" and ("rom", s) not in seen)
    extra["header_structs"] = header_structs
    # the per-family register aliases (include/task_vars.h, #155 run 5)
    aliases = {}
    vars_h = os.path.join(ROOT, "include", "task_vars.h")
    if os.path.exists(vars_h):
        fam = None
        for line in read("include/task_vars.h").split("\n"):
            m = re.match(r"/\* ([A-Z]\w*) - ", line)
            if m:
                fam = m.group(1)
            m = re.match(r"#define (\w+) (unk[0-9A-F]+) ", line)
            if m and fam:
                aliases.setdefault(fam, []).append(m.group(1))
    extra["aliases"] = aliases
    # the named constants (include/constants/, tools/constants.py, #155 run 6)
    extra["constants"] = None
    if os.path.isdir(os.path.join(ROOT, "include", "constants")):
        spec = importlib.util.spec_from_file_location(
            "constants", os.path.join(ROOT, "tools", "constants.py"))
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        extra["constants"] = mod.census()
    # loc_ labels
    loc = 0
    for top in ("asm", "src", "include", "data"):
        for path in files_under(top, (".s", ".c", ".h", ".inc")):
            loc += len(re.findall(r"^\s*loc_[0-9A-Fa-f]{8}:", read(path), re.M))
    add("label", "loc", loc)
    return rows, by_zone, extra


def category_reason(cat):
    if cat in REASONS:
        return REASONS[cat]
    code = cat.split(":", 1)[1]
    if code == "unexamined":
        return "NOT EXAMINED: no row in %s (the audit fails)" % UNNAMED_CSV
    return UNNAMED_REASONS.get(code, "unknown reason code `%s` (the audit fails)" % code)


def census_markdown(rows, by_zone, extra):
    out = [CENSUS_BEGIN, ""]
    out.append("| kind | placeholder | count | reason |")
