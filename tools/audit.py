# 5. code exceptions

# Checked in order; the first match names the line's kind.
EXC_PATTERNS = (
    ("pin", re.compile(r"\bregister\b[^;]*\basm\s*\(")),
    ("cross-jump", re.compile(r"\bBLOCK_CROSS_JUMP\b")),
    ("alias", re.compile(r"\)\s*(?:asm|__asm__)\s*\(\s*\"\w+\"\s*\)\s*;")),
    ("lever", re.compile(r"\b(?:asm|__asm__)\s*(?:volatile\s*|__volatile__\s*)?\(\s*\"\"")),
    ("inline-asm", re.compile(r"\b(?:asm|__asm__)\s*(?:volatile\s*|__volatile__\s*)?\(")),
    ("zero-code", re.compile(r"\bwhile\s*\(\s*0\s*\)")),
)
EXC_KINDS = "pin|lever|cross-jump|alias|inline-asm|zero-code|stand-in"
EXC_ROW_RE = re.compile(
    r"^\|\s*`(src/[\w./-]+\.c):(\d+)(?:-(\d+))?`\s*\|\s*`?(\w+|\(file scope\))`?\s*\|\s*(" + EXC_KINDS + r")\s*\|\s*(.+?)\s*\|\s*$")
FILE_SCOPE = "(file scope)"


def function_of_lines(stripped):
    """The function each line (1-based list index - 1) lies in, from brace
    depth: a `{` at depth 0 preceded by `name(...)` opens function `name`."""
    funcs = []
    depth = 0
    current = None
    pending = ""
    for line in stripped.split("\n"):
        at_start = current if depth > 0 else None
        for k, c in enumerate(line):
            if c == "{":
                if depth == 0:
                    before = (pending + " " + line[:k])
                    m = re.search(r"([A-Za-z_]\w*)\s*\([^()]*(?:\([^()]*\)[^()]*)*\)\s*$", before)
                    current = m.group(1) if m else None
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0:
                    current = None
            elif c == ";" and depth == 0:
                pending = ""
        funcs.append(at_start if at_start is not None else (current if depth > 0 else None))
        pending = (pending + " " + line)[-400:] if depth == 0 else ""
    return funcs


def enclosing_function(lines, ln):
    funcs = function_of_lines(strip_c("\n".join(lines)))
    f = funcs[ln - 1] if 0 < ln <= len(funcs) else None
    return f or FILE_SCOPE


def scan_exceptions():
    found = []
    for path in files_under("src", (".c",)):
        text = read(path)
        stripped = strip_c(text)
        funcs = function_of_lines(stripped)
        for ln, line in enumerate(stripped.split("\n"), 1):
            for kind, pat in EXC_PATTERNS:
                if pat.search(line):
                    found.append((path, ln, kind, funcs[ln - 1] or FILE_SCOPE))
                    break
    return found


def check_exceptions(rep, listing):
    doc = read(AUDIT_DOC) if os.path.exists(os.path.join(ROOT, AUDIT_DOC)) else ""
    body = doc_section(doc, 3) or ""
    rows = []
    for line in body.split("\n"):
        m = EXC_ROW_RE.match(line)
        if m:
            first = int(m.group(2))
            last = int(m.group(3) or m.group(2))
            rows.append((m.group(1), first, last, m.group(4), m.group(5), m.group(6)))
    found = scan_exceptions()
    covered = set()
    for path, first, last, func, kind, why in rows:
        if not os.path.exists(os.path.join(ROOT, path)):
            rep.fail("%s section 3: %s does not exist" % (AUDIT_DOC, path))
            continue
        hits = [f for f in found if f[0] == path and first <= f[1] <= last and f[2] == kind]
        if kind == "stand-in":
            lines = read(path).split("\n")
            if last > len(lines) or enclosing_function(lines, first) != func:
                rep.fail("%s section 3: %s:%d is not inside %s any more" % (AUDIT_DOC, path, first, func))
            continue
        if not hits:
            rep.fail("%s section 3: no %s at %s:%d-%d any more" % (AUDIT_DOC, kind, path, first, last))
        for h in hits:
            covered.add(h)
            if h[3] != func:
                rep.fail("%s section 3: %s:%d is in %s, not %s" % (AUDIT_DOC, path, h[1], h[3], func))
    for f in found:
        if f not in covered:
            rep.fail("code exception not listed in %s section 3: %s:%d (%s, in %s)"
                     % (AUDIT_DOC, f[0], f[1], f[2], f[3]))
    counts = {}
    for f in found:
        counts[f[2]] = counts.get(f[2], 0) + 1
    standins = sum(1 for r in rows if r[4] == "stand-in")
    lines = ["mechanically found: %s" % ", ".join("%s %d" % (k, counts[k]) for k in sorted(counts)),
             "documented rows: %d (of which stand-in rows: %d)" % (len(rows), standins)]
    funcs = sorted({r[3] for r in rows})
    lines.append("functions with an exception: %d (%s)" % (len(funcs), ", ".join(funcs)))
    if listing:
        lines += ["  %s:%d %s in %s" % f for f in found]
    rep.section("5. Code exceptions", lines)
    return {"found": counts, "rows": len(rows), "functions": funcs}


