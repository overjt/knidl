# 4. raw addresses in src/ and include/*.h

ADDR_RE = re.compile(r"\b0[xX]0*([2-9A-Ea-e])([0-9A-Fa-f]{6})[uUlL]*\b")
REGION_NAMES = {
    0x2: "EWRAM", 0x3: "IWRAM", 0x4: "I/O", 0x5: "palette", 0x6: "VRAM",
    0x7: "OAM", 0x8: "ROM", 0x9: "ROM", 0xA: "ROM", 0xB: "ROM", 0xC: "ROM",
    0xD: "ROM", 0xE: "SRAM",
}
CONTROL_WORD_CALLS = ("CpuSet", "CpuFastSet")


def enclosing_call(stripped, pos):
    """(callee, is_last_argument) of the innermost call around pos."""
    depth = 0
    i = pos - 1
    while i >= 0:
        c = stripped[i]
        if c in ")]}":
            depth += 1
        elif c in "([{":
            if depth == 0:
                if c != "(":
                    return None, False
                m = re.search(r"([A-Za-z_]\w*)\s*$", stripped[:i])
                callee = m.group(1) if m else None
                # last argument: no top-level comma between pos and the ')'
                d = 0
                j = pos
                while j < len(stripped):
                    cj = stripped[j]
                    if cj in "([{":
                        d += 1
                    elif cj in ")]}":
                        if d == 0:
                            return callee, True
                        d -= 1
                    elif cj == "," and d == 0:
                        return callee, False
                    j += 1
                return callee, False
            depth -= 1
        elif c == ";" and depth == 0:
            return None, False
        i -= 1
    return None, False


def check_raw_addresses(rep, listing):
    paths = files_under("src", (".c", ".h")) + [
        p for p in files_under("include", (".h",)) if not p.startswith("include/gba/")]
    justified, control, bad = [], [], []
    for path in paths:
        text = read(path)
        raw_lines = text.split("\n")
        stripped = strip_c(text)
        line_starts = [0]
        for k, c in enumerate(stripped):
            if c == "\n":
                line_starts.append(k + 1)
        for m in ADDR_RE.finditer(stripped):
            ln = _line_of(line_starts, m.start())
            region = REGION_NAMES[int(m.group(1), 16)]
            item = "%s:%d: %s (%s): %s" % (path, ln, m.group(0), region, raw_lines[ln - 1].strip())
            callee, last = enclosing_call(stripped, m.start())
            if callee in CONTROL_WORD_CALLS and last:
                control.append(item)
                continue
            here = raw_lines[ln - 1]
            above = raw_lines[ln - 2] if ln >= 2 else ""
            if "raw:" in here or "raw:" in above:
                justified.append(item)
            else:
                bad.append(item)
    for b in bad:
        rep.fail("raw address without a symbol, macro or `raw:` comment: " + b)
    lines = [
        "control words (last argument of CpuSet/CpuFastSet): %d" % len(control),
        "justified (`raw:` comment): %d" % len(justified),
        "unjustified: %d" % len(bad),
    ]
    by_region = {}
    for b in bad:
        r = b.split("(", 1)[1].split(")", 1)[0]
        by_region[r] = by_region.get(r, 0) + 1
    for r in sorted(by_region):
        lines.append("  unjustified %s: %d" % (r, by_region[r]))
    if listing:
        lines += ["  " + j for j in justified]
        lines += ["  UNJUSTIFIED " + b for b in bad]
    rep.section("4. Raw addresses in src/ and include/*.h", lines)
    return {"control_words": len(control), "justified": len(justified), "unjustified": len(bad)}


def _line_of(starts, pos):
    lo, hi = 0, len(starts)
    while lo + 1 < hi:
        mid = (lo + hi) // 2
        if starts[mid] <= pos:
            lo = mid
        else:
            hi = mid
    return lo + 1


