# 2. raw numeric directives in asm/

RAW_DIRECTIVE_RE = re.compile(
    r"^\s*(?:[A-Za-z_.$][\w.$]*:\s*)?\.(byte|short|hword|half|2byte|inst|inst\.n|inst\.w|word|4byte|long|int)\b\s*(.*)$")
NUMBER_RE = re.compile(r"^[-+~]?\s*(?:0[xX][0-9A-Fa-f]+|0[bB][01]+|\d+|'.')$")


def asm_code_and_comment(line):
    """Split a gas ARM line into its code and its comment (@ or /* */)."""
    code, comment = line, ""
    at = line.find("@")
    if at >= 0:
        code, comment = line[:at], line[at + 1:]
    m = re.search(r"/\*(.*?)(\*/|$)", code)
    if m:
        comment = (m.group(1) + " " + comment).strip()
        code = code[:m.start()]
    return code, comment


def check_raw_directives(rep, listing):
    rows = []
    unjustified = []
    for path in files_under("asm", (".s", ".inc")):
        for ln, line in enumerate(read(path).split("\n"), 1):
            code, comment = asm_code_and_comment(line)
            m = RAW_DIRECTIVE_RE.match(code)
            if not m:
                continue
            ops = [o.strip() for o in m.group(2).split(",") if o.strip()]
            if not any(NUMBER_RE.match(o) for o in ops):
                continue
            why = re.search(r"\braw:\s*(.*)$", comment)
            item = "%s:%d: .%s %s" % (path, ln, m.group(1), ", ".join(ops))
            if why:
                rows.append((path, item, why.group(1).strip()))
            else:
                unjustified.append(item)
    for u in unjustified:
        rep.fail("raw numeric directive without an `@ raw:` reason: " + u)
    by_file = {}
    for path, _, _ in rows:
        by_file[path] = by_file.get(path, 0) + 1
    lines = ["justified (`@ raw:` on the line): %d" % len(rows),
             "unjustified: %d" % len(unjustified)]
    for path in sorted(by_file):
        lines.append("  %s: %d justified" % (path, by_file[path]))
    if listing:
        lines += ["  " + item + "  -- " + why for _, item, why in rows]
        lines += ["  UNJUSTIFIED " + u for u in unjustified]
    rep.section("2. Raw numeric directives in asm/", lines)
    return {"justified": len(rows), "unjustified": len(unjustified)}


